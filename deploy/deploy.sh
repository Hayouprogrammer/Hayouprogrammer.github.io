#!/usr/bin/env bash
#
# deploy.sh — build here, ship there, reload Caddy.
#
#   ./deploy/deploy.sh user@your-vps.example.com your-domain.example.com
#
# Run from the repository root. Two arguments: the SSH destination, and the
# domain the site will be served on. Both are required — a default would be a
# guess, and guessing the destination of a deploy is how you publish to the
# wrong box.
#
# WHAT IT DOES
#   1. Builds with SITE_URL pointed at the real domain, so every canonical URL,
#      the sitemap and the QR target agree with the address people will use.
#   2. rsyncs the build output and the deploy configuration to the VPS.
#   3. Reloads Caddy, which picks up the new files with zero downtime — the
#      container is not recreated unless the image changed.
#
# Why rsync and not a git pull on the box: the box needs one directory and one
# configuration file. It does not need a git remote, a node runtime, a lockfile
# or the build toolchain, and it definitely does not need the ability to run
# npm install. Everything that could break in production is left at home.
#
set -euo pipefail

REMOTE="${1:-}"
DOMAIN="${2:-}"

if [[ -z "$REMOTE" || -z "$DOMAIN" ]]; then
  echo "usage: $0 <user@host> <domain>" >&2
  echo "   e.g. $0 deploy@imbirt.example.com imbirt.example.com" >&2
  exit 2
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REMOTE_DIR="/opt/portfolio"

cd "$ROOT"

echo "==> building for https://${DOMAIN}"
SITE_URL="https://${DOMAIN}" npm run build

# The QR codes are generated by hand against the printed target, deliberately,
# because a stale code on a leaflet is permanent. Warn rather than silently
# overwrite: this is the one artefact that must never be regenerated by a deploy.
if [[ -d dist/qr ]]; then
  echo "    note: dist/qr is being shipped as built. Confirm the codes point at"
  echo "          https://${DOMAIN} before printing anything. (node scripts/make-qr.mjs)"
fi

echo "==> shipping to ${REMOTE}:${REMOTE_DIR}"
ssh "$REMOTE" "mkdir -p ${REMOTE_DIR}"
# --delete so a removed screenshot does not stay served forever. The dist/ tree
# is entirely generated, so there is nothing there worth protecting from it.
rsync -az --delete \
  --exclude '.git' \
  dist/ "${REMOTE}:${REMOTE_DIR}/dist/"
rsync -az deploy/ "${REMOTE}:${REMOTE_DIR}/deploy/"

echo "==> writing the domain into the environment"
# Written on the box, not in the repo: the domain is deployment configuration and
# a second deployment of the same build should not require a rebuild.
ssh "$REMOTE" "cat > ${REMOTE_DIR}/deploy/.env" <<EOF
SITE_DOMAIN=${DOMAIN}
ACME_EMAIL=admin@${DOMAIN}
EOF

echo "==> reloading Caddy"
# `up -d` is a no-op when nothing changed, which is what makes redeploys
# instantaneous. The container is only recreated if the image or the compose
# file actually differs.
ssh "$REMOTE" "cd ${REMOTE_DIR}/deploy && docker compose up -d"

echo
echo "==> live: https://${DOMAIN}"
echo "    check: curl -I https://${DOMAIN}/imbirt  (expect 301 to /work/imbirt)"
